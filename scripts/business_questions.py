"""Answer the six business questions from both pipelines' final tables and
write docs/business_questions.md (SQL + result for each).

    python scripts/business_questions.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import duckdb  # noqa: E402

from include.nammamart.config import ELT_DAG_ID, ETL_DAG_ID, WAREHOUSE_PATH  # noqa: E402

Q = [
    ("Q1a. Daily net revenue by zone (delivered orders, after discount)",
     """SELECT order_date, zone, net_revenue
FROM etl_daily_zone_revenue
ORDER BY order_date, zone""",
     """SELECT order_date, zone, round(sum(net_revenue), 2) AS net_revenue
FROM mart_daily_store_kpis
GROUP BY 1, 2 HAVING sum(delivered_orders) > 0
ORDER BY order_date, zone""", 10),
    ("Q1b. Daily net revenue by store",
     """SELECT f.order_date, f.store_id, s.store_name, s.zone,
       round(sum(f.net_revenue), 2) AS net_revenue
FROM etl_fact_orders f JOIN etl_dim_store s USING (store_id)
WHERE f.order_status = 'DELIVERED'
GROUP BY ALL ORDER BY f.order_date, f.store_id""",
     """SELECT order_date, store_id, store_name, zone, net_revenue
FROM mart_daily_store_kpis
WHERE delivered_orders > 0
ORDER BY order_date, store_id""", 8),
    ("Q1c. September total by zone (summary of Q1a)",
     """SELECT zone, round(sum(net_revenue), 2) AS sept_net_revenue
FROM etl_daily_zone_revenue
WHERE order_date < DATE '2026-10-01'
GROUP BY zone ORDER BY sept_net_revenue DESC""",
     """SELECT zone, round(sum(net_revenue), 2) AS sept_net_revenue
FROM mart_daily_store_kpis
WHERE order_date < DATE '2026-10-01'
GROUP BY zone ORDER BY sept_net_revenue DESC""", 10),
    ("Q2. Revenue and gross margin by category",
     """SELECT category, revenue, cost, gross_margin, margin_pct
FROM etl_category_margin ORDER BY revenue DESC""",
     """SELECT category, revenue, cost, gross_margin, margin_pct
FROM mart_category_margin ORDER BY revenue DESC""", 10),
    ("Q3. Average delivery time per store and % delivered within 15 minutes",
     """SELECT f.store_id, s.store_name,
       round(avg(f.delivery_minutes), 1) AS avg_delivery_minutes,
       round(100.0 * avg(CAST(f.within_15_min AS INTEGER)), 1) AS pct_within_15_min
FROM etl_fact_orders f JOIN etl_dim_store s USING (store_id)
WHERE f.order_status = 'DELIVERED'
GROUP BY ALL ORDER BY pct_within_15_min DESC, f.store_id""",
     """SELECT store_id, store_name, avg_delivery_minutes, pct_within_15_min
FROM mart_delivery_sla ORDER BY pct_within_15_min DESC, store_id""", 15),
    ("Q4a. Revenue by payment mode",
     """SELECT payment_mode, count(*) AS delivered_orders, round(sum(net_revenue), 2) AS net_revenue
FROM etl_fact_orders WHERE order_status = 'DELIVERED'
GROUP BY 1 ORDER BY net_revenue DESC""",
     """SELECT payment_mode, count(*) AS delivered_orders, round(sum(order_amount), 2) AS net_revenue
FROM stg_orders WHERE dq_status <> 'FAIL' AND order_status = 'DELIVERED'
GROUP BY 1 ORDER BY net_revenue DESC""", 10),
    ("Q4b. Amount that doesn't reconcile with the payment gateway",
     """SELECT coalesce(mismatch_reason, 'TOTAL') AS mismatch_reason, count(*) AS cases,
       round(sum(abs(amount_difference)), 2) AS amount
FROM etl_payment_reconciliation GROUP BY ROLLUP (mismatch_reason)
ORDER BY grouping(mismatch_reason), mismatch_reason""",
     """SELECT coalesce(mismatch_reason, 'TOTAL') AS mismatch_reason, count(*) AS cases,
       round(sum(abs(amount_difference)), 2) AS amount
FROM mart_payment_reconciliation GROUP BY ROLLUP (mismatch_reason)
ORDER BY grouping(mismatch_reason), mismatch_reason""", 10),
    ("Q5. Top 10 customers by spend, with loyalty tier (masked contact details only)",
     """SELECT f.customer_id, c.customer_name_masked, c.email_masked, c.loyalty_tier,
       round(sum(f.net_revenue), 2) AS total_spend
FROM etl_fact_orders f JOIN etl_dim_customer c USING (customer_id)
WHERE f.order_status = 'DELIVERED'
GROUP BY ALL ORDER BY total_spend DESC, f.customer_id LIMIT 10""",
     """SELECT customer_id, customer_name_masked, email_masked, loyalty_tier, total_spend
FROM mart_top_customers ORDER BY spend_rank""", 10),
    ("Q6. Rows rejected in the latest run, by file and reason",
     """SELECT source_file, failure_reason, count(*) AS rows_rejected
FROM etl_quarantine
WHERE run_id = (SELECT run_id FROM pipeline_runs WHERE dag_id = '{etl}' ORDER BY end_time DESC LIMIT 1)
GROUP BY ALL ORDER BY source_file, rows_rejected DESC""",
     """SELECT source_file, failure_reason, rows_rejected
FROM mart_rejections ORDER BY source_file, rows_rejected DESC""", 30),
]


def main():
    con = duckdb.connect(str(WAREHOUSE_PATH), read_only=True)
    md = ["# Business questions: SQL and results from both pipelines", "",
          "Generated by `scripts/business_questions.py` after a run that included the "
          "1 Oct increment. Long results are truncated; run the SQL for the full table.", ""]
    for title, etl_sql, elt_sql, limit in Q:
        etl_sql = etl_sql.format(etl=ETL_DAG_ID)
        a = con.execute(etl_sql).fetchdf()
        b = con.execute(elt_sql).fetchdf()
        same = a.astype(str).values.tolist() == b.astype(str).values.tolist()
        md += [f"## {title}", "", "**ETL** (`etl_*` tables)", "", "```sql", etl_sql, "```", "",
               "**ELT** (`mart_*` / `stg_*` tables)", "", "```sql", elt_sql, "```", "",
               f"Result ({len(a)} rows; ETL and ELT results {'identical' if same else 'DIFFER'}):", "",
               a.head(limit).to_markdown(index=False, floatfmt=".2f"), ""]
        if len(a) > limit:
            md += [f"_... {len(a) - limit} more rows_", ""]
        print(f"{'OK  ' if same else 'DIFF'} {title}")
    (ROOT / "docs" / "business_questions.md").write_text("\n".join(md))
    print("written docs/business_questions.md")


if __name__ == "__main__":
    main()
